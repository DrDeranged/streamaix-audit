function formatUsd(value: number): string {
  if (value >= 1e12) return `$${(value / 1e12).toFixed(2)}T`;
  if (value >= 1e9) return `$${(value / 1e9).toFixed(2)}B`;
  if (value >= 1e6) return `$${(value / 1e6).toFixed(2)}M`;
  return `$${value.toLocaleString('en-US', { maximumFractionDigits: 2 })}`;
}

function numberValue(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value);
}

/** Factual fallback used when the reasoning gateway is unavailable. */
function factualAlphaDesk(pulse: MarketPulse): AlphaDeskObservation[] {
  const rows: AlphaDeskObservation[] = [];
  const add = (text: string, section: any) => {
    if (!findBannedAdvice(text)) rows.push({ text, asOf: section.asOf, delayed: section.delayed });
  };
  const volumeCount = pulse.unusualVolumeCount?.data;
  if (numberValue(volumeCount)) add(`${volumeCount} assets are flagged for unusual volume.`, pulse.unusualVolumeCount);
  const horizon = Date.now() + 7 * 24 * 60 * 60 * 1000;
  for (const earning of pulse.earnings?.data || []) {
    const date = new Date(earning.date);
    if (earning.symbol && !Number.isNaN(date.getTime()) && date.getTime() <= horizon && date.getTime() >= Date.now()) {
      add(`${earning.symbol.toUpperCase()} has earnings scheduled on ${earning.date}.`, pulse.earnings);
    }
  }
  const marketCap = pulse.totalMarketCap?.data?.value;
  if (numberValue(marketCap)) add(`Total market capitalization is ${formatUsd(marketCap)}.`, pulse.totalMarketCap);
  const dominance = pulse.btcDominance?.data?.value;
  if (numberValue(dominance)) add(`Bitcoin dominance is ${dominance.toFixed(2)}%.`, pulse.btcDominance);
  const fear = pulse.fearGreed?.data;
  const fearValue = typeof fear === 'number' ? fear : fear?.value;
  if (numberValue(fearValue)) add(`The crypto Fear & Greed reading is ${fearValue}/100.`, pulse.fearGreed);
  for (const mover of (pulse.movers?.data || []).slice(0, 2)) {
    if (mover.symbol && numberValue(mover.change24h)) {
      add(`${mover.symbol.toUpperCase()} moved ${mover.change24h >= 0 ? '+' : ''}${mover.change24h.toFixed(2)}% over 24 hours.`, pulse.movers);
    }
  }
  return rows.slice(0, 5);
}

/**
 * Ask the reasoning tier for concise observations, then validate each bullet
 * independently. Invalid bullets are dropped rather than rewritten.
 */
export async function generateAlphaDesk(pulse: MarketPulse | null | undefined): Promise<AlphaDeskObservation[]> {
  if (!pulse) return [];
  const fallback = factualAlphaDesk(pulse);
  if (fallback.length === 0) return [];

  try {
    const result = await modelGateway.completeJson<{ bullets?: unknown[] }>({
      tier: 'reasoning',
      priority: 'background',
      tag: 'newsletter-alpha-desk',
      system: 'Select and order 3-5 observations from the supplied canonical candidates. Do not rewrite them or add facts. Return JSON: {"bullets":[{"id":0,"text":"<exact candidate text>"}]}.',
      user: JSON.stringify({
        asOf: pulse.asOf,
        delayed: pulse.delayed,
        candidates: fallback.map((candidate, id) => ({ id, ...candidate })),
        data: pulse
      }),
      maxTokens: 500,
      jsonSchema: {
        name: 'newsletter_alpha_desk',
        schema: { type: 'object', properties: { bullets: { type: 'array', items: { type: 'object', properties: { id: { type: 'integer' }, text: { type: 'string' } }, required: ['id', 'text'] } } }, required: ['bullets'] }
      }
    });
    const bullets = Array.isArray(result?.bullets) ? result.bullets : [];
    const accepted: AlphaDeskObservation[] = bullets
      .map((bullet: unknown): AlphaDeskObservation | null => {
        const id = typeof bullet === 'object' && bullet !== null && 'id' in bullet
          ? Number((bullet as { id?: unknown }).id) : -1;
        const text = typeof bullet === 'object' && bullet !== null && 'text' in bullet
          ? (bullet as { text?: unknown }).text : bullet;
        const candidate = Number.isInteger(id) && id >= 0 && id < fallback.length
          ? fallback[id] : fallback.find(item => item.text === text);
        // The server emits only an exact canonical candidate. A rewritten
        // sentence, even with matching numbers/symbols, is rejected.
        if (!candidate || typeof text !== 'string' || text !== candidate.text || findBannedAdvice(text)) return null;
        if (findBannedAdvice(candidate.text)) return null;
        return candidate;
      })
      .slice(0, 5)
      .filter((item): item is AlphaDeskObservation => item !== null);
    return accepted;
  } catch (error: any) {
    console.warn('Alpha Desk generation failed, using factual observations:', error?.message || error);
    return fallback;
  }
}

const MEME_COIN_PATTERNS = [
  'inu', 'shib', 'doge', 'pepe', 'elon', 'floki', 'baby',
  'moon', 'safe', 'rocket', 'meme', 'wojak', 'chad',
  'bonk', 'bome', 'wif', 'pepe2', 'dogelon'
];

function isMemeCoin(name: string, symbol: string): boolean {
  const lowerName = name.toLowerCase();
  const lowerSymbol = symbol.toLowerCase();
  return MEME_COIN_PATTERNS.some(pattern =>
    lowerName.includes(pattern) || lowerSymbol.includes(pattern)
  );
}

function calculateRelevanceScore(coin: any): number {
  const marketCapWeight = Math.log10(coin.marketCap || 1);
  const volumeWeight = Math.log10(coin.volume24h || 1);
  const priceChangeWeight = Math.abs(coin.percentChange24h);
  return marketCapWeight * volumeWeight * priceChangeWeight;
}

