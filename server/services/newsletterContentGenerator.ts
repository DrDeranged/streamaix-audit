/**
 * Fetch Fear & Greed Index from Alternative.me API
 */
async function fetchFearGreedIndex(): Promise<number | null> {
  try {
    const response = await fetch('https://api.alternative.me/fng/?limit=1');
    const data = await response.json();
    if (data && data.data && data.data[0]) {
      return parseInt(data.data[0].value, 10);
    }
    return null;
  } catch (error) {
    if (!fearGreedWarned) {
      fearGreedWarned = true;
      console.warn('Fear & Greed fetch failed; omitting unavailable value:', error);
    }
    return null;
  }
}

const MIN_MARKET_TRADERS = 25;

function formatResolvesLabel(deadline: Date): string {
  return deadline.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    timeZone: 'America/New_York'
  });
}

/**
 * Fetch hot prediction markets from database.
 * Only active markets whose deadline is in the future qualify; markets with
 * fewer than MIN_MARKET_TRADERS traders are excluded, unless we'd otherwise
 * end up with fewer than 2 markets — in that case the largest future-dated
 * market is included regardless of trader count.
 */
export async function fetchHotMarkets(now: Date = new Date()): Promise<HotMarket[]> {
  try {
    const markets = await db.select()
      .from(predictionMarkets)
      .where(eq(predictionMarkets.status, 'active'))
      .orderBy(desc(predictionMarkets.totalVolume))
      .limit(25);

    const futureMarkets = markets.filter(m => {
      const deadline = m.deadline ? new Date(m.deadline) : null;
      return deadline !== null && deadline.getTime() > now.getTime();
    });

    let qualified = futureMarkets.filter(m => (m.totalTrades || 0) >= MIN_MARKET_TRADERS);

    if (qualified.length < 2 && futureMarkets.length > 0) {
      // Include the largest future-dated market (by volume) regardless of
      // trader count rather than showing expired markets.
      const extras = futureMarkets
        .filter(m => !qualified.includes(m))
        .sort((a, b) => (b.totalVolume || 0) - (a.totalVolume || 0));
      qualified = [...qualified, ...extras.slice(0, 2 - qualified.length)];
    }

    return qualified.slice(0, 5).map(m => {
      const yesPrice = m.yesPrice || 5000;
      const yesPercent = Math.round((yesPrice / 10000) * 100);
      return {
        question: m.question,
        yesPercent,
        volume: m.totalVolume || 0,
        traders: m.totalTrades || 0,
        resolves: formatResolvesLabel(new Date(m.deadline))
      };
    });
  } catch (error) {
    console.error('Error fetching hot markets:', error);
    return [];
  }
}

/**
 * Fetch top stock movers from Finnhub API. Missing quotes are omitted.
 */
async function fetchStockMovers(): Promise<{ gainers: StockHighlight[]; losers: StockHighlight[]; spy: { price: number; change: number } }> {
  try {
    const movers = await stockMarketService.getTechAiMovers();

    const formatStock = (s: any): StockHighlight => ({
      symbol: s.symbol,
      name: s.name,
      price: s.price,
      change: s.change,
      changePercent: s.changePercent,
      isPositive: s.changePercent > 0,
      sector: s.sector
    });

    const gainers = movers.gainers.slice(0, 5).map(formatStock);
    const losers = movers.losers.slice(0, 5).map(formatStock);

    let spyData = { price: 0, change: 0 };
    try {
      const spyQuote = await stockMarketService.getStockQuote('SPY');
      if (spyQuote && spyQuote.c > 0) {
        spyData = { price: spyQuote.c, change: Number.isFinite(spyQuote.dp) ? spyQuote.dp : 0 };
      }
    } catch (e) {
      console.warn('Failed to fetch SPY quote; omitting unavailable quote');
    }

    return { gainers, losers, spy: spyData };
  } catch (error) {
    console.error('Error fetching stock movers:', error);
    return {
      gainers: [],
      losers: [],
      spy: { price: 0, change: 0 }
    };
  }
}

/** Get a date's calendar parts as they appear in the America/New_York timezone. */
function getEtParts(date: Date): { year: number; month: number; day: number; hour: number; minute: number; second: number } {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/New_York',
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour: 'numeric',
    minute: 'numeric',
    second: 'numeric',
    hour12: false
  }).formatToParts(date);
  const get = (type: string) => parseInt(parts.find(p => p.type === type)?.value || '0', 10);
  return {
    year: get('year'),
    month: get('month'),
    day: get('day'),
    hour: get('hour') % 24,
    minute: get('minute'),
    second: get('second')
  };
}

function formatEtDateLabel(date: Date): string {
  return date.toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
    timeZone: 'America/New_York'
  });
}

/**
 * Get upcoming scheduled streams (daily 8:00 AM / 4:00 PM Eastern market updates).
 * Times are computed in America/New_York regardless of the server timezone,
 * and labeled "ET" (never a hardcoded "EST").
 */
export async function fetchUpcomingStreams(now: Date = new Date()): Promise<UpcomingStream[]> {
  try {
    const et = getEtParts(now);
    const DAY_MS = 24 * 60 * 60 * 1000;
    const etSecondsOfDay = et.hour * 3600 + et.minute * 60 + et.second;

    // A slot rolls to tomorrow only once its exact ET time has strictly passed;
    // at exactly 8:00:00 / 4:00:00 PM ET the just-starting stream stays today.
    const morningDate = etSecondsOfDay > 8 * 3600 ? new Date(now.getTime() + DAY_MS) : now;
    const afternoonDate = etSecondsOfDay > 16 * 3600 ? new Date(now.getTime() + DAY_MS) : now;

    return [
      {
        title: 'Morning Market Update',
        time: `${formatEtDateLabel(morningDate)} · 8:00 AM ET`,
        emoji: '🌅'
      },
      {
        title: 'Market Close Recap',
        time: `${formatEtDateLabel(afternoonDate)} · 4:00 PM ET`,
        emoji: '🌙'
      }
    ];
  } catch (error) {
    console.error('Error fetching upcoming streams:', error);
    return [];
  }
}

interface BriefInputs {
  btcPrice: number;
  btcChange: number;
  ethPrice: number;
  ethChange: number;
  spyPrice: number;
  spyChange: number;
  fearGreedIndex: number | null;
  stockGainers: StockHighlight[];
  stockLosers: StockHighlight[];
  topCryptoMover?: MarketHighlight;
}

function signedPct(n: number): string {
  return `${n >= 0 ? '+' : ''}${n.toFixed(2)}%`;
}

function fallbackBrief(i: BriefInputs): string {
  const dir = i.btcChange >= 0 ? 'rose' : 'fell';
  const stats = [
    i.btcPrice > 0 ? `Bitcoin ${dir} ${signedPct(i.btcChange)} to $${i.btcPrice.toLocaleString('en-US', { maximumFractionDigits: 0 })}` : null,
    i.ethPrice > 0 ? `Ether moved ${signedPct(i.ethChange)}` : null,
    i.spyPrice > 0 ? `SPY (S&P 500 ETF) changed ${signedPct(i.spyChange)}` : null,
    i.fearGreedIndex === null ? null : `crypto sentiment sits at ${i.fearGreedIndex}/100`
  ].filter(Boolean);
  return `${stats.join('; ')}.`;
}

/**
 * Generate "The Agents' Brief": a single 90–130 word editorial paragraph via
 * the model gateway. Observational and specific, never advisory. If the
 * gateway call fails for any reason, falls back to a plain factual sentence —
 * the newsletter is never sent without a brief and the send never crashes.
 */
export async function generateAgentsBrief(inputs: BriefInputs): Promise<string> {
  const {
    btcPrice, btcChange, ethPrice, ethChange, spyPrice, spyChange,
  fearGreedIndex, stockGainers, stockLosers, topCryptoMover
  } = inputs;

  const gainersDesc = stockGainers.slice(0, 3)
    .map(s => `${s.symbol} ${signedPct(s.changePercent)}`).join(', ') || 'none';
  const losersDesc = stockLosers.slice(0, 3)
    .map(s => `${s.symbol} ${signedPct(s.changePercent)}`).join(', ') || 'none';
  const cryptoMoverDesc = topCryptoMover
    ? `${topCryptoMover.symbol} ${signedPct(topCryptoMover.changePercent)}`
    : 'none';

  try {
    const result = await modelGateway.complete({
      tier: 'reasoning',
      priority: 'background',
      tag: 'newsletter-content-generator',
      system:
        'You are the editor of a financial newsletter written by autonomous AI trading agents. ' +
        'Write a single paragraph of 90-130 words summarizing today\'s market. Be observational ' +
        'and specific: reference the actual numbers you are given, and note tensions in the data ' +
        '(for example a fear reading while prices rise). NEVER give advice or recommendations — ' +
        'do not use words like "consider", "buy", "sell", or "opportunity", and do not suggest ' +
        'positioning of any kind. Plain prose only, no headings, no bullet points, no markdown.',
      user:
        `Today's data:\n` +
        `${btcPrice > 0 ? `- Bitcoin: $${btcPrice.toLocaleString('en-US', { maximumFractionDigits: 2 })} (${signedPct(btcChange)} 24h)\n` : ''}` +
        `${ethPrice > 0 ? `- Ethereum: $${ethPrice.toLocaleString('en-US', { maximumFractionDigits: 2 })} (${signedPct(ethChange)} 24h)\n` : ''}` +
        `${spyPrice > 0 ? `- SPY (S&P 500 ETF): ${signedPct(spyChange)} on the day\n` : ''}` +
       `${fearGreedIndex === null ? '' : `- Crypto Fear & Greed index: ${fearGreedIndex}/100\n`}` +
        `- Top stock gainers: ${gainersDesc}\n` +
        `- Top stock losers: ${losersDesc}\n` +
        `- Top crypto mover: ${cryptoMoverDesc}`,
      maxTokens: 400
    });
    const text = (result.content || '').trim();
    if (!text) return fallbackBrief(inputs);
    return text;
  } catch (error: any) {
    console.warn('Agents\' Brief generation failed, using factual fallback:', error?.message || error);
    return fallbackBrief(inputs);
  }
}

/**
 * Generate newsletter content from live crypto market data.
 * Data is provider-backed only. Unavailable providers are omitted rather than
 * represented with simulated market numbers.
 */
export async function generateNewsletterContent(): Promise<NewsletterContent> {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
  const dayOfWeek = now.toLocaleDateString('en-US', { weekday: 'long' });
  const subject = `📈 StreamAiX Market Alpha - ${dayOfWeek}, ${dateStr}`;

  try {
    const [rawCryptoData, fearGreedIndex, hotMarkets, upcomingStreams, stockData, marketPulse] = await Promise.all([
      fetchCryptoDataDirectFromCoinGecko(50),
      fetchFearGreedIndex(),
      fetchHotMarkets(),
      fetchUpcomingStreams(),
      fetchStockMovers(),
      getMarketPulse().catch((error: any) => {
        console.warn('Alpha Desk market pulse unavailable:', error?.message || error);
        return null;
      })
    ]);

    const cryptoData = rawCryptoData;

    const filteredCoins = cryptoData.filter(coin =>
      !isMemeCoin(coin.name, coin.symbol) &&
      coin.marketCap > 100000000 &&
      coin.volume24h > 1000000
    );

    const allCoins: (MarketHighlight & { relevanceScore: number })[] = filteredCoins.map(coin => ({
      symbol: coin.symbol.toUpperCase(),
      name: coin.name,
      price: coin.price,
      change24h: (coin.price * coin.percentChange24h) / 100,
      changePercent: coin.percentChange24h,
      isPositive: coin.percentChange24h > 0,
      relevanceScore: calculateRelevanceScore(coin)
    }));

    const gainers = allCoins
      .filter(c => c.isPositive)
      .sort((a, b) => b.relevanceScore - a.relevanceScore);

    const losers = allCoins
      .filter(c => !c.isPositive)
      .sort((a, b) => b.relevanceScore - a.relevanceScore);

    const topGainers = gainers.slice(0, 5);
    const topLosers = losers.slice(0, 5);
    const marketHighlights = allCoins.slice(0, 3);

    const btcData = allCoins.find(c => c.symbol === 'BTC');
    const ethData = allCoins.find(c => c.symbol === 'ETH');

    const topCryptoMover = [...topGainers, ...topLosers]
      .sort((a, b) => Math.abs(b.changePercent) - Math.abs(a.changePercent))[0];

    const agentsBrief = await generateAgentsBrief({
      btcPrice: btcData?.price || 0,
      btcChange: btcData?.changePercent || 0,
      ethPrice: ethData?.price || 0,
      ethChange: ethData?.changePercent || 0,
      spyPrice: stockData.spy.price,
      spyChange: stockData.spy.change,
      fearGreedIndex,
      stockGainers: stockData.gainers,
      stockLosers: stockData.losers,
      topCryptoMover
    });
    const alphaDesk = await generateAlphaDesk(marketPulse as MarketPulse | null);

    let newsStories: Array<{ title: string; url: string; source: string; published: string }> = [];
    try {
      const { marketDataService } = await import('./marketDataService');
      const newsArticles = await marketDataService.getFinancialNews(5);
      newsStories = newsArticles.map(article => ({
        title: article.title,
        url: article.url,
        source: article.source || 'CoinDesk',
        published: article.published
      }));
    } catch (error) {
      console.error('Error fetching news stories:', error);
    }

    return {
      subject,
      marketHighlights,
      topGainers,
      topLosers,
      stockGainers: stockData.gainers,
      stockLosers: stockData.losers,
      agentsBrief,
      alphaDesk,
      cryptoAsOf: lastGoodCrypto?.asOf,
      cryptoDelayed: cryptoFetchDelayed,
      totalMarketCap: numberValue(marketPulse?.totalMarketCap?.data?.value) ? formatUsd(marketPulse.totalMarketCap.data.value) : 'N/A',
      btcDominance: numberValue(marketPulse?.btcDominance?.data?.value) ? `${marketPulse.btcDominance.data.value.toFixed(2)}%` : 'N/A',
      btcPrice: btcData?.price || 0,
      btcChange: btcData?.changePercent || 0,
      ethPrice: ethData?.price || 0,
      ethChange: ethData?.changePercent || 0,
      spyPrice: stockData.spy.price,
      spyChange: stockData.spy.change,
      fearGreedIndex,
      hotMarkets,
      upcomingStreams,
      newsStories
    };
  } catch (error) {
    console.error('Error generating newsletter content; omitting unavailable provider data:', error);

    const fearGreed = await fetchFearGreedIndex().catch(() => null);
    const upcomingStreams = await fetchUpcomingStreams().catch(() => []);
    const hotMarkets = await fetchHotMarkets().catch(() => []);
    return {
      subject,
      marketHighlights: [],
      topGainers: [],
      topLosers: [],
      stockGainers: [],
      stockLosers: [],
      agentsBrief: '',
      alphaDesk: [],
      totalMarketCap: 'N/A',
      btcDominance: 'N/A',
      btcPrice: 0,
      btcChange: 0,
      ethPrice: 0,
      ethChange: 0,
      spyPrice: 0,
      spyChange: 0,
      fearGreedIndex: fearGreed,
      hotMarkets,
      upcomingStreams,
      newsStories: []
    };
  }
}

