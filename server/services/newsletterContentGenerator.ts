/**
 * Fetch top cryptos directly from CoinGecko Pro API.
 * Falls back to public CoinGecko if Pro key is missing.
 * Returns an empty array only if both fail.
 */
async function fetchCryptoDataDirectFromCoinGecko(limit: number = 50): Promise<CryptoQuoteSimple[]> {
  const proKey = process.env.COINGECKO_PRO_API_KEY || '';
  const baseUrl = proKey
    ? 'https://pro-api.coingecko.com/api/v3'
    : 'https://api.coingecko.com/api/v3';
  const headers: Record<string, string> = proKey
    ? { 'x-cg-pro-api-key': proKey }
    : {};

  try {
    const response = await axios.get(`${baseUrl}/coins/markets`, {
      headers,
      params: {
        vs_currency: 'usd',
        order: 'market_cap_desc',
        per_page: limit,
        page: 1,
        sparkline: false,
        price_change_percentage: '24h'
      },
      timeout: 10000
    });

    if (!response.data || !Array.isArray(response.data)) {
      throw new Error('Invalid CoinGecko response');
    }

    const data = response.data
      .map((coin: any): CryptoQuoteSimple | null => {
        const values = [coin.current_price, coin.price_change_percentage_24h, coin.market_cap, coin.total_volume];
        if (!coin.symbol || !coin.name || values.some(value => typeof value !== 'number' || !Number.isFinite(value))) return null;
        return {
          symbol: coin.symbol.toUpperCase(), name: coin.name,
          price: coin.current_price, percentChange24h: coin.price_change_percentage_24h,
          marketCap: coin.market_cap, volume24h: coin.total_volume
        };
      })
      .filter((coin: CryptoQuoteSimple | null): coin is CryptoQuoteSimple => coin !== null);
    if (!data.length) throw new Error('CoinGecko returned no valid quotes');
    cryptoFetchDelayed = false;
    lastGoodCrypto = { data, asOf: new Date().toISOString() };
    return data;
  } catch (error: any) {
    cryptoFetchDelayed = true;
    if (!coinGeckoWarned) {
      coinGeckoWarned = true;
      console.warn('CoinGecko fetch failed; using last known-good data when available:', error.message);
    }
    return lastGoodCrypto?.data || [];
  }
}

